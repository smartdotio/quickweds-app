// One-off generator: copies the SVG data for the icons the app uses out of
// lucide-react (ISC) into src/components/icons.tsx, so the app doesn't depend
// on the 4,500-file package at runtime.
// Usage: npm i --no-save lucide-react && node scripts/gen-icons.mjs ArrowRight Check ...
// Pass every icon name the app imports (existing ones are overwritten).
import { readFileSync, writeFileSync } from "node:fs";

const names = process.argv.slice(2);
const dir = "node_modules/lucide-react/dist/esm";
const barrel = readFileSync(`${dir}/lucide-react.mjs`, "utf8");

const out = [];
for (const name of names) {
  const m = barrel.match(new RegExp(`default as ${name}\\b[^}]*\\} from '\\./icons/([\\w-]+)\\.mjs'`));
  if (!m) throw new Error(`No icon ${name}`);
  const { __iconData } = await import(`../${dir}/icons/${m[1]}.mjs`);
  const node = __iconData.node.map(([tag, attrs]) => [tag, Object.fromEntries(Object.entries(attrs).filter(([k]) => k !== "key"))]);
  out.push(`export const ${name} = icon(${JSON.stringify(node)});`);
}

writeFileSync(
  "src/components/icons.tsx",
  `// Icon outlines from Lucide (https://lucide.dev), ISC License,
// Copyright (c) Lucide Icons and Contributors. Generated by scripts/gen-icons.mjs.
import { createElement, type SVGProps } from "react";

type Node = [string, Record<string, string>][];
export type IconProps = SVGProps<SVGSVGElement> & { size?: number | string; strokeWidth?: number | string };

function icon(node: Node) {
  return function Icon({ size = 24, strokeWidth = 2, className, ...rest }: IconProps) {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden={rest["aria-label"] ? undefined : true}
        className={className}
        {...rest}
      >
        {node.map(([tag, attrs], i) => createElement(tag, { key: i, ...attrs }))}
      </svg>
    );
  };
}

${out.join("\n")}
`,
);
console.log(`wrote ${out.length} icons`);
