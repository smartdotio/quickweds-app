// Regenerates supabase/seed.sql from src/lib/routes-seed.ts.
// Run: node scripts/gen-seed.ts
import { writeFileSync } from "node:fs";
import { ROUTE_SEED } from "../src/lib/routes-seed.ts";

const q = (v: unknown) => (v === null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const lines: string[] = ["-- Generated by scripts/gen-seed.ts — do not edit by hand.", ""];
ROUTE_SEED.forEach((r, i) => {
  lines.push(
    `insert into public.routes (id, slug, name, country, tagline, funds, funds_note, weights, source_url, verified_at, position) values (${q(r.id)}, ${q(r.slug)}, ${q(r.name)}, ${q(r.country)}, ${q(r.tagline)}, ${j(r.funds)}, ${q(r.fundsNote)}, ${j(r.weights)}, ${q(r.sourceUrl)}, null, ${i}) on conflict (id) do nothing;`,
  );
  for (const s of r.stages)
    lines.push(
      `insert into public.route_stages (id, route_id, position, title, description) values (${q(s.id)}, ${q(r.id)}, ${s.position}, ${q(s.title)}, ${q(s.description)}) on conflict (id) do nothing;`,
    );
  r.documents.forEach((d, k) =>
    lines.push(
      `insert into public.route_documents (id, route_id, key, label, weight, help, position) values (${q(d.id)}, ${q(r.id)}, ${q(d.key)}, ${q(d.label)}, ${d.weight}, ${q(d.help)}, ${k}) on conflict (id) do nothing;`,
    ),
  );
  lines.push("");
});

lines.push(
  `insert into public.products (slug, name, description, price_kobo) values ('strategy-session', 'Strategy Session', '45-minute 1-on-1 video session, written action plan within 48 hours, 30 days of portal access.', 4500000) on conflict (slug) do nothing;`,
  `insert into public.settings (key, value) values ('fx', '{"ngnPerEur": 1700, "updatedAt": "2026-10-29"}'::jsonb) on conflict (key) do nothing;`,
  `insert into public.settings (key, value) values ('quick_tags', ${j([
    "Police clearance must be under 3 months old",
    "Translation must be by a sworn translator",
    "Page missing — please upload all pages",
    "Scan unreadable — please re-scan in colour",
    "Name doesn't match passport",
    "Document must be legalised",
  ])}) on conflict (key) do nothing;`,
  "",
  "-- After your first login, promote yourself:",
  "-- update public.profiles set role = 'admin' where email = 'you@example.com';",
);

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n") + "\n");
console.log("supabase/seed.sql written");
